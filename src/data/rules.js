export const RULES = Object.fromEntries(
  rows.map(([id, name, condition, exclusion]) => [
    id,
    {
      id,
      name,
      version: VERSION.rules,
      condition,
      exclusion,
      pages: ['本質', '財運', '緣分', '流年大運', '五行取用喜忌神'],
    },
  ]),
);
export function trace(id, passed, facts, decision) {
  if (!RULES[id]) throw Error(`未註冊規則 ${id}`);
  return {
    rule: id,
    version: VERSION.rules,
    passed,
    condition: RULES[id].condition,
    exclusion: RULES[id].exclusion,
    facts,
    decision,
  };
}
