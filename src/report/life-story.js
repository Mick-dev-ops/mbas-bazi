export function lifeProfile(a) {
  const primary = a.patterns.monthJudgment.name;
  const secondary =
    a.patterns.assist.find((x) => a.facts.gods[x] >= 0.2 && x !== primary) ||
    god(a.facts.dm, HIDDEN[a.chart.pillars[2].branch][0]);
  const inner = god(a.facts.dm, HIDDEN[a.chart.pillars[2].branch][0]);
  const p = LIFE_STYLE[primary];
  const s = LIFE_STYLE[secondary];
  const i = LIFE_STYLE[inner];
  const weak = a.strength.state === '承格不足';
  const concentrated = a.strength.concentrated;
  const pressure = PRESSURE_SCENE[a.diagnosis.primary.id] || PRESSURE_SCENE.none;
  const tension = weak
    ? `外界要求一多，${p.strain}。這不是能力不足，而是你需要先有支持、休息與可承擔的範圍。`
    : concentrated
      ? `你有持續投入的韌性，但也可能因為太能撐而忽略自己同樣需要${i.need}；越疲累時，越要避免只靠意志維持。`
      : `你能在不同情境間調整，但${p.need}與${s.need}都需要被照顧，否則容易一邊配合、一邊失去自己的步調。`;
  const loadScene = weak
    ? '當要求同時增加時，你會先犧牲休息與自己的安排；外表仍在配合，內在卻會逐漸失去餘裕'
    : concentrated
      ? '你很能靠自己的方式維持局面，但撐得越久，越容易把求助、退讓或單純享受生活視為不必要'
      : '你通常能隨情境調整，但若長期只照顧外在期待，內在真正重視的步調仍會以疲累或疏離提醒你';
  const overview = `${OUTER_SCENE[primary]}；${INNER_SCENE[inner]}。${loadScene}。因此你一生真正要練習的，不是把所有情境都處理好，而是${pressure.turn}。`;
  const diseaseLesson = `${pressure.scene}。較適合的轉向是：${pressure.turn}。`;
  return {
    primary,
    secondary,
    inner,
    conclusion: `你的人生本質是${p.nature}，內在同時${i.nature}。`,
    overview,
    overviewPractice: `最適合你的日常不是一味追求輕鬆，也不是不停證明自己，而是同時保留${p.joy}，並用「${pressure.turn}」檢查重要選擇。`,
    coreNeed: `真正重要的需求是${p.need}；在親近關係裡，還需要${i.need}。`,
    gift: `${p.gift}；${s.gift}。`,
    conflict: `關係有摩擦時，${p.strain}；若同時缺少理解或休息，${s.strain}。`,
    tension,
    lesson: diseaseLesson,
    joy: `容易讓你感到真實滿足的生活包括：${p.joy}。${i.joy}也能補回內在能量。`,
    recovery: `累的時候，先${p.recovery}；若情緒仍沒有回來，再${i.recovery}。`,
    lifeRule:
      PATTERN_LIFE[a.patterns.primary.id] ||
      '你適合在保有自己步調的前提下，逐步建立穩定的關係、興趣與生活安排；外在成就用來支持人生，不用拿來取代人生。',
    stages: [
      `早年：先認識自己真正喜歡與不喜歡的事，允許嘗試，不必太早用單一標準定義自己。`,
      `成年：在各種責任與關係之外保留${p.need}，重要選擇以能否長期維持身心餘裕判斷。`,
      `中年：把已經證明過的能力轉成更自由的選擇，減少只因習慣、面子或他人期待而留下的責任。`,
      `晚年：生活重心回到${i.joy}；保留自主、陪伴與可安心使用的資源，不以持續忙碌證明價值。`,
    ],
  };
}
